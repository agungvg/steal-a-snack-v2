#!/usr/bin/env python3
"""Assemble the headless test run into one Luau chunk.

Standalone Luau gives every required file its own global environment, so
the mock Roblox globals set in tests/mock.luau would be invisible inside
src/shared/Config.luau and friends. The fix is textual: concatenate the
REAL source files (mock, Config, CharacterFactory, Weather, run_tests)
into tests/_combined.luau and run that single chunk. Nothing is copied
by hand — the combined file is regenerated from the sources on every run,
so the tests always exercise the actual game code.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load_module(rel_path):
    text = (ROOT / rel_path).read_text()
    # Drop ONLY the module's trailing `return X` line (the last
    # non-empty line); its top-level `local X` stays in scope for the
    # rest of the combined chunk. Returns inside functions are kept.
    lines = text.splitlines()
    for i in range(len(lines) - 1, -1, -1):
        if lines[i].strip() == "":
            continue
        if re.match(r"^return \w+$", lines[i].strip()):
            del lines[i]
        break
    # Drop `local X = require(...)` lines: in the combined chunk the
    # required module is already a top-level local in scope (Config is
    # loaded first), and standalone Luau has no require/game globals.
    # Bases.luau is the only source module that requires anything.
    lines = [ln for ln in lines if not re.match(r"^\s*local \w+ = require\(", ln)]
    return "\n".join(lines)


def load_tests():
    text = (ROOT / "tests" / "run_tests.luau").read_text()
    # The require block at the top is replaced by the assembled modules.
    lines = text.splitlines()
    lines = [ln for ln in lines if not ln.startswith("require(")]
    return "\n".join(lines)


parts = [
    "-- AUTO-GENERATED by tests/assemble.py — do not edit. Run tests/run.sh.",
    load_module("tests/mock.luau"),
    load_module("src/shared/Config.luau"),
    load_module("src/server/CharacterFactory.luau"),
    load_module("src/server/Weather.luau"),
    load_module("src/server/Bases.luau"),
    load_tests(),
]
out = ROOT / "tests" / "_combined.luau"
out.write_text("\n\n".join(parts) + "\n")
print(f"assembled {out}")
